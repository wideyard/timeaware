"""日常活动持续时间类QA生成器"""

from llm_client import call_llm_json

SYSTEM_PROMPT = """你是一个时间推理benchmark数据集的生成器。你需要生成关于日常活动持续时间的推理题目。

核心目标：测试模型对时间流逝的物理感知能力，而非简单的数字计算。

要求：
1. 题目必须结合现实世界的物理规律
2. 需要推算事件耗时，并理解时间累积造成的物理后果
3. 场景应贴近日常生活（做饭、通勤、运动等）
4. 四个选项中必须有一个是基于正确时间推理的答案
5. 错误选项应该是对时间流逝或物理后果的误解

【关键】确保答案唯一性：
- 必须确保正确答案在给定条件下是唯一合理的
- 选项之间应该有明确的区分度
- 避免多个选项都"可能正确"的情况

【重要】选项设计原则：
- 选项只包含纯粹的答案文本，不要添加任何解释
- 例如：A. 鸡肉烤得刚刚好，蔬菜略软 （不要写成 "鸡肉烤得刚刚好，蔬菜略软（正确）"）

输出格式：JSON
{
    "question": "问题文本",
    "options": {
        "A": "选项A",
        "B": "选项B",
        "C": "选项C",
        "D": "选项D"
    },
    "answer": "A/B/C/D",
    "explanation": "解释时间推理过程和物理后果",
    "time_calculation": "具体的时间计算过程",
    "physical_consequence": "时间累积造成的物理后果说明"
}"""


def generate_duration_qa(count: int = 15) -> list:
    """生成日常活动持续时间类QA题目"""
    questions = []
    
    prompt = f"""请生成{count}道关于日常活动持续时间的推理题目。

核心要求：
1. 题目场景必须涉及物理世界的时间累积效应
2. 需要推算多个活动的总耗时
3. 必须理解时间流逝对物理世界的影响（如食物烹饪、冰融化、水蒸发等）
4. 场景示例：
   - 煮饺子/面条离开一段时间后的状态
   - 冰淇淋放在桌上一段时间后的状态
   - 衣服晾晒在不同天气下的干燥速度
   - 长时间运动后的身体状态

【关键】确保答案唯一性：
- 设计题目时，必须明确"在常温/标准条件下"的结果
- 选项应该有明确的物理状态区分
- 避免两个选项都"可能正确"的情况

【示例 - 确保唯一答案】
好例子：
问题：你在厨房里煮饺子，水开后煮了8分钟。然后你把饺子捞出，放在盘子里，再过了5分钟后准备吃。这时饺子最可能的状态是？
选项：
A. 仍然很热，几乎没有降温（错误，5分钟足以降温）
B. 温度已经降到接近室温（正确）
C. 表面凉了但内部还很烫（可能，但5分钟后整体应该接近室温）
D. 已经完全凉透（错误，5分钟不够完全凉透）

更好的例子（更明确）：
问题：你在厨房里煮饺子，水开后煮了8分钟。然后你把饺子捞出，放在盘子里，再过了15分钟后准备吃。室温25℃。这时饺子最可能的状态是？
选项：
A. 仍然很热，几乎没有降温（错误）
B. 温度已经降到接近室温（约25-30℃）（正确）
C. 完全凉透，冰凉（错误，15分钟通常不会完全凉透）
D. 表面凉了但内部还很烫（错误，15分钟后整体应该接近室温）

请生成{count}道不同的题目，以JSON数组格式返回：
[{{
    "question": "...",
    "options": {{"A": "...", "B": "...", "C": "...", "D": "..."}},
    "answer": "A/B/C/D",
    "explanation": "...",
    "time_calculation": "...",
    "physical_consequence": "..."
}}, ...]"""

    try:
        result = call_llm_json(prompt, SYSTEM_PROMPT)
        if isinstance(result, list):
            for i, q in enumerate(result):
                q["id"] = f"duration_{i+1:03d}"
                q["type"] = "duration"
            questions = result
    except Exception as e:
        print(f"生成持续时间QA失败: {e}")
    
    return questions
