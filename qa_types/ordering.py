"""事件先后顺序类QA生成器"""

from llm_client import call_llm_json

SYSTEM_PROMPT = """你是一个时间推理benchmark数据集的生成器。你需要生成关于事件排序的推理题目。

核心目标：给定多个具有不同耗时、不同时间窗口限制的事件，考察模型的拓扑排序与规划能力。

要求：
1. 包含多个需要完成的任务
2. 每个任务有：耗时、时间窗口限制、地点
3. 需要考虑任务之间的路程时间
4. 正确答案是唯一可行的执行顺序
5. 错误选项必须导致明确的任务失败或时间冲突

【关键】必须确保：
1. 正确答案真的是唯一满足所有约束的顺序
2. 每个错误选项都必须产生明确的时间冲突（某个任务无法在deadline前完成）
3. 验证每个选项的时间可行性

【重要】选项设计原则：
- 选项只包含纯粹的顺序文本，不要添加任何解释
- 例如：A. 开会 -> 去银行 -> 取快递 （不要写成 "开会 -> 去银行 -> 取快递（正确）"）

输出格式：JSON
{
    "question": "问题文本",
    "tasks": [
        {"name": "任务名", "duration": "耗时", "deadline": "截止时间", "constraint": "其他约束"}
    ],
    "current_time": "当前时间",
    "options": {
        "A": "顺序A",
        "B": "顺序B",
        "C": "顺序C",
        "D": "顺序D"
    },
    "answer": "A/B/C/D",
    "explanation": "为什么这个顺序可行，其他顺序为什么失败",
    "timeline": "最优顺序的时间线"
}"""


def generate_ordering_qa(count: int = 15) -> list:
    """生成事件先后顺序类QA题目"""
    questions = []
    
    prompt = f"""请生成{count}道关于事件排序的推理题目。

【关键要求】
1. 场景：某人需要在限定时间内完成多个任务
2. 每个任务包含：
   - 任务名称（如：去银行、取快递、开会等）
   - 所需时间（如：30分钟、1小时等）
   - 时间窗口（如：下午4点前、仅2-3点有空等）
   - 地点（如：市中心、公司附近等）

3. 必须设计使多个选项产生不同结果：
   - 正确答案：满足所有deadline的可行顺序
   - 错误选项：必须导致至少一个任务无法在deadline前完成
   
4. 【重要】验证每个选项的时间可行性：
   - 标注每个任务开始和结束时间
   - 确认正确答案真的能在所有deadline前完成
   - 确认每个错误选项真的会导致某个任务超时

【示例 - 必须保证唯一正确答案】

当前时间：下午2点
任务：
1. 开会：1小时，deadline：下午3点前，公司
2. 去银行：30分钟，deadline：下午4点前，市中心
3. 取快递：15分钟，deadline：下午4点前，公司附近

分析：
- 选项A（开会->去银行->取快递）：2-3点开会，3-3:30银行，3:30-3:45取快递 ✓全部满足
- 选项B（取快递->去银行->开会）：2-2:15取快递，2:15-2:45银行，...开会4点才能开始，错过deadline ✗
- 选项C（去银行->取快递->开会）：2-2:30银行，...取快递3点后才能开始，可能超时 ✗
- 选项D（开会->取快递->去银行）：2-3点开会，...取快递3:30后才能开始，银行4点deadline紧张 ✓但不是最优

正确答案应该设计为A（最优或唯一完全可行）

请生成{count}道不同的题目，以JSON数组格式返回：
[{{
    "question": "...",
    "tasks": [...],
    "current_time": "...",
    "options": {{"A": "...", "B": "...", "C": "...", "D": "..."}},
    "answer": "A/B/C/D",
    "explanation": "...",
    "timeline": "..."
}}, ...]"""

    try:
        result = call_llm_json(prompt, SYSTEM_PROMPT)
        if isinstance(result, list):
            for i, q in enumerate(result):
                q["id"] = f"ordering_{i+1:03d}"
                q["type"] = "ordering"
            questions = result
    except Exception as e:
        print(f"生成事件排序QA失败: {e}")
    
    return questions
